import assert from 'node:assert/strict';
import { createSceneHistoryStore } from '../../src/scene-history.js';
import { createLegacyAdapter, sceneHistoryDomain } from '../../src/store/legacy-adapter.js';
import { documentFixture } from './document-store-fixture.mjs';

const scene = createSceneHistoryStore([], {});
const legacy = createLegacyAdapter({ objects: sceneHistoryDomain(scene) });
const { store, bus, run, register } = documentFixture({ legacy });
register('objects.set', 'objects', ({ value }) => { store.write('objects', [{ id: 'cube', x: value }]); });
try {
  const stage = run('stage.set', { value: 2 });
  legacy.write('objects', [{ id: 'cube', x: 1 }]);
  const objectEntry = store.history().present.historyEntryId;
  assert.equal(store.depths().past, 2);
  assert.equal(scene.depths().past, 1);
  assert.equal(run('edit.undo', { receiptId: stage.receiptId }).code, 'UNDO_CONFLICT');
  assert.equal(store.undo().historyEntryId, objectEntry);
  assert.deepEqual(scene.objects, []);
  assert.equal(store.read('stage').intensity, 2);
  assert.equal(run('edit.undo', { receiptId: stage.receiptId }).status, 'undone');
  assert.equal(store.read('stage').intensity, 1);
  store.redo(); store.redo();
  assert.deepEqual(scene.objects, [{ id: 'cube', x: 1 }]);
  assert.equal(store.read('stage').intensity, 2);
  const newerStage = run('stage.set', { value: 3 });
  assert.equal(store.undo().historyEntryId, newerStage.undo.historyEntryId);
  assert.equal(store.undo().historyEntryId, objectEntry, 'native scene and store undo interleave in both directions');
  const tx = run('run.begin', { id: 'objects.set', args: { value: 1 } });
  run('run.update', { txId: tx.txId, args: { value: 3 } });
  run('run.update', { txId: tx.txId, args: { value: 4 } });
  assert.equal(run('run.cancel', { txId: tx.txId }).ok, true);
  assert.deepEqual(scene.objects, []);
  register('stage.composite', 'stage', ({ value }, context) => {
    store.write('stage', { intensity: value });
    context.run('objects.set', { value });
  });
  const beforeDepth = store.depths().past;
  const compound = run('stage.composite', { value: 8 });
  assert.equal(compound.ok, true, JSON.stringify(compound));
  assert.equal(store.depths().past, beforeDepth + 1, 'mixed ownership is one receipt and one logical history entry');
  assert.equal(run('edit.undo', { receiptId: compound.receiptId }).status, 'undone');
  assert.deepEqual(scene.objects, []);
  assert.equal(store.read('stage').intensity, 2);
  store.redo();
  assert.equal(scene.objects[0].x, 8);
  assert.equal(store.read('stage').intensity, 8);
  assert.ok([...store.history().past, store.history().present, ...store.history().future].every(entry => !Object.hasOwn(entry.snapshot, 'objects')));
  scene.applyAtomic(() => [{ id: 'external' }]);
  assert.equal(store.canUndo(compound.undo.historyEntryId), false, 'an uncoordinated native edit must not be silently undone');
  assert.throws(() => store.undo(), { code: 'UNDO_CONFLICT' });
} finally { bus.dispose(); store.dispose(); legacy.dispose(); }
console.log('PASS document store 6: native scene/store undo ordering, wire cancellation and atomic mixed-domain history');
