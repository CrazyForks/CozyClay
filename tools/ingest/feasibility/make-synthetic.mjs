/**
 * Synthetic ground-truth generator for the Phase-0 feasibility runners (F2a-F2c).
 *
 * WHY this exists: nobody can run GVHMR on this workstation, so the runners can never be
 * exercised against real solver output. This module builds the next best thing -- a scene
 * whose world roots, foot contacts, identity assignments and separation are known exactly
 * -- projects those positions through the plan's pinned camera (plan 9.1 geometry: K,
 * centre (0, 2.60, -7.50), look-at (0, 0, 0.60)), and emits the RawTrack-shaped
 * observations the runners consume plus the 10.2 solver-output fixtures F2r/F3 replay.
 * The fixture is the solver output on synthetic GT, which IS the ground truth by
 * construction; a runner must reproduce it to float noise.
 *
 * Scene model (deliberately simple, and why): the solved root is the PLANTED FOOT on the
 * ring floor (y = floorY), not the pelvis -- M3 measures "solved planted-foot world XZ",
 * M5 compares the solved root against hand-annotated FOOT world positions, M6 measures
 * inter-fighter separation, all foot-level quantities. A fighter stands in a constant
 * stance (one foot planted, contact 0.93; the other lifted 0.15 m, contact 0.07) and hops
 * to the next stance at a phase boundary; within a stance the planted foot, and therefore
 * the root, is exactly constant, which is what makes M3 = 0 and M5 = 0 exact rather than
 * approximate. The manual-anchor fixture anchors every stance start AND end with the
 * stance's own value, so linear interpolation between anchors reproduces the step-function
 * GT exactly; on real footage the operator's marks would not align this well, which is
 * exactly what M5 is for.
 *
 * Determinism is a contract: no randomness anywhere, and every emitted document carries a
 * sha256 over itself with the sha256 field excluded, so a checked-in fixture can be
 * verified and regenerated byte-for-byte.
 *
 * @feasibility-only -- disposable Phase-0 feasibility code (plan 10.2). NOT production:
 * no envelope integration, no HTTP route, no UI, no contract obligations, no provenance emission,
 * no error taxonomy. Mechanically fenced (6.2): nothing outside
 * tools/ingest/feasibility/** and test/ingest/** may import it. Removed in Stage B.
 */
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { solveManualAnchor } from "./manual-anchor.mjs";

