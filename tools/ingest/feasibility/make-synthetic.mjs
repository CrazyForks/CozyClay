// --- tiny 3-vector / 3x3 helpers ------------------------------------------------------

const sub = (a, b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
const normalize = (v) => {
	const n = Math.hypot(v[0], v[1], v[2]);
	return [v[0] / n, v[1] / n, v[2] / n];
};
const cross = (a, b) => [
	a[1] * b[2] - a[2] * b[1],
	a[2] * b[0] - a[0] * b[2],
	a[0] * b[1] - a[1] * b[0],
];
// row-major matvec: result[i] = row i of m dotted with v
const matVec = (m, v) => [
	m[0][0] * v[0] + m[0][1] * v[1] + m[0][2] * v[2],
	m[1][0] * v[0] + m[1][1] * v[1] + m[1][2] * v[2],
	m[2][0] * v[0] + m[2][1] * v[1] + m[2][2] * v[2],
];
const transpose = (m) => [
	[m[0][0], m[1][0], m[2][0]],
	[m[0][1], m[1][1], m[2][1]],
	[m[0][2], m[1][2], m[2][2]],
];
function mat3Inv(m) {
	const [a, b, c] = m[0];
	const [d, e, f] = m[1];
	const [g, h, i] = m[2];
	const A = e * i - f * h;
	const B = -(d * i - f * g);
	const C = d * h - e * g;
	const det = a * A + b * B + c * C;
	if (det === 0) throw new Error("make-synthetic: singular matrix");
	return [
		[A / det, (c * h - b * i) / det, (b * f - c * e) / det],
		[B / det, (a * i - c * g) / det, (c * d - a * f) / det],
		[C / det, (b * g - a * h) / det, (a * e - b * d) / det],
	];
}

// --- camera (plan 8.1 convention: p_ring = R_ring_from_cam * p_cam + t) ----------------

function lookAtExtrinsics(centre, lookAt, up) {
	// camera frame: z forward, x image-right, y image-down (OpenCV-style pinhole); R's
	// COLUMNS are the camera axes in ring coordinates, so p_cam = R^T * (p_ring - t).
	const z = normalize(sub(lookAt, centre));
	const x = normalize(cross(up, z));
	const y = cross(x, z);
	const R = [
		[x[0], y[0], z[0]],
		[x[1], y[1], z[1]],
		[x[2], y[2], z[2]],
	];
	return { R, t: centre };
}

function projectToPixels(p, K, R, t) {
	const pc = matVec(transpose(R), sub(p, t));
	return [K[0][0] * (pc[0] / pc[2]) + K[0][2], K[1][1] * (pc[1] / pc[2]) + K[1][2]];
}

// --- ground truth ----------------------------------------------------------------------

function phaseAt(trackId, f) {
	const phases = SCENE.phases[trackId];
	for (let i = 0; i < phases.length; i += 1) {
		if (f >= phases[i].from && f < phases[i].to) return i;
	}
	throw new Error(`make-synthetic: frame ${f} outside all phases of ${trackId}`);
}

function groundTruth(trackId) {
	const rootWorld = [];
	const plantedSide = [];
	const footWorld = { left: [], right: [] };
	for (let f = 0; f < SCENE.frames; f += 1) {
		const i = phaseAt(trackId, f);
		const pos = SCENE.phases[trackId][i].pos;
		const side = i % 2 === 0 ? "left" : "right";
		const swing = i === 0 ? [pos[0] + SCENE.swingOffset[trackId][0], pos[1] + SCENE.swingOffset[trackId][1]] : SCENE.phases[trackId][i - 1].pos;
		rootWorld.push([pos[0], SCENE.floorY, pos[1]]);
		plantedSide.push(side);
		footWorld.left.push(side === "left" ? [pos[0], SCENE.floorY, pos[1]] : [swing[0], SCENE.swingLiftM, swing[1]]);
		footWorld.right.push(side === "right" ? [pos[0], SCENE.floorY, pos[1]] : [swing[0], SCENE.swingLiftM, swing[1]]);
	}
	return { rootWorld, plantedSide, footWorld };
}

function contactMaskOf(plantedSide) {
	return plantedSide.map((side) => [
		side === "left" ? SCENE.contactPlanted : SCENE.contactSwing,
		side === "right" ? SCENE.contactPlanted : SCENE.contactSwing,
	]);
}

function handLabels(gt) {
	// the 100 hand-labelled frames, per subject: label[subjectId][i] = [leftFoot,
	// rightFoot] booleans equal to the GT contacts -- a perfect annotator, which is
	// what the synthetic control needs. M2 judges each subject's contacts against its
	// own labels.
	return Object.fromEntries(
		SCENE.subjects.map((s) => {
			const planted = gt[s.trackId].plantedSide;
			return [
				s.subjectId,
				SCENE.handContactFrames.map((f) => [planted[f] === "left", planted[f] === "right"]),
			];
		}),
	);
}

// --- document hashing ------------------------------------------------------------------

export function sha256Of(doc) {
	return createHash("sha256").update(JSON.stringify(doc)).digest("hex");
}

export function verifySha256(doc) {
	if (typeof doc.sha256 !== "string" || !/^[0-9a-f]{64}$/.test(doc.sha256)) return false;
	const copy = JSON.parse(JSON.stringify(doc));
	delete copy.sha256;
	return sha256Of(copy) === doc.sha256;
}

// --- emitted documents -----------------------------------------------------------------

function buildRawTrack(gt, R, t) {
	const frameIndex = Array.from({ length: SCENE.frames }, (_, f) => f);
	const timeS = frameIndex.map((f) => f / SCENE.fps);
	const subjects = SCENE.subjects.map((s) => {
		const g = gt[s.trackId];
		const obs = (side) => ({
			foot: side,
			observationSpace: "full-image",
			// one keypoint per frame: [u, v] pixels, origin top-left (F1-d naming)
			keypoints: g.footWorld[side].map((p) => projectToPixels(p, SCENE.K, R, t)),
		});
		return {
			trackId: s.trackId,
			footObservations2d: { left: obs("left"), right: obs("right") },
			leftContact: g.plantedSide.map((side) => (side === "left" ? SCENE.contactPlanted : SCENE.contactSwing)),
			rightContact: g.plantedSide.map((side) => (side === "right" ? SCENE.contactPlanted : SCENE.contactSwing)),
			confidence: Array(SCENE.frames).fill(SCENE.confidence),
		};
	});
	const doc = {
		schemaVersion: 1,
		clipId: SCENE.clipId,
		fps: SCENE.fps,
		frames: SCENE.frames,
		frameIndex,
		timeS,
		K: SCENE.K,
		subjects,
	};
	doc.sha256 = sha256Of(doc);
	return doc;
}

function buildFloorFrame(R, t) {
	const doc = {
		schemaVersion: 1,
		clipId: SCENE.clipId,
		K: SCENE.K,
		R_ring_from_cam: R,
		t_ring_from_cam: t,
		floorY: SCENE.floorY,
		planeNormal_ring: [0, 1, 0],
		metresPerUnit: 1.0,
		// the synthetic control's calibration is perfect by construction
		quality: { heldOutErrorM: 0, uncertainty1SigmaM: 0, inlierRatio: 1, reprojRmsPx: 0, conditionNumber: 1, ropeStraightnessPx: 0 },
	};
	doc.sha256 = sha256Of(doc);
	return doc;
}

function buildAnnotation(gt) {
	const frameIndex = SCENE.scoredFrames;
	const pos = (trackId) => frameIndex.map((f) => gt[trackId].rootWorld[f]);
	const doc = {
		schemaVersion: 2,
		clipId: SCENE.clipId,
		handContact: { frameIndex: SCENE.handContactFrames, label: handLabels(gt) },
		// foot world positions on the same frames M4/M5/M6 score (F2r cross-checks this)
		footWorld: { frameIndex, A: pos("p0"), B: pos("p1") },
	};
	doc.sha256 = sha256Of(doc);
	return doc;
}

function buildFixture(mode, gt, rawTrack, floorFrame, annotation, R, t) {
	const frameIndex = Array.from({ length: SCENE.frames }, (_, f) => f);
	const timeS = frameIndex.map((f) => f / SCENE.fps);
	const rootsByMode = {
		// on synthetic GT the contact-head and lowest-foot solver output IS the ground
		// truth; the manual-anchor fixture carries the interpolant of its own anchors,
		// which the anchor scheme (stance start AND end per value) makes equal to GT.
		"contact-head": () => SCENE.subjects.map((s) => gt[s.trackId].rootWorld),
		"lowest-foot": () => SCENE.subjects.map((s) => gt[s.trackId].rootWorld),
		"manual-anchor": () => {
			const anchors = {};
			for (const s of SCENE.subjects) {
				anchors[s.trackId] = SCENE.phases[s.trackId].flatMap((p) => [
					{ frameIndex: p.from, world: [p.pos[0], SCENE.floorY, p.pos[1]] },
					{ frameIndex: p.to, world: [p.pos[0], SCENE.floorY, p.pos[1]] },
				]);
			}
			return solveManualAnchor(rawTrack, floorFrame, anchors).subjects.map((s) => s.rootWorld);
		},
	};
	const rootWorlds = rootsByMode[mode]();
	const doc = {
		schemaVersion: 2,
		clipId: SCENE.clipId,
		mode,
		fps: SCENE.fps,
		frames: SCENE.frames,
		frameIndex,
		timeS,
		subjects: SCENE.subjects.map((s, i) => ({
			subjectId: s.subjectId,
			trackId: s.trackId,
			rootWorld: rootWorlds[i],
			contactMask: contactMaskOf(gt[s.trackId].plantedSide),
			confidence: Array(SCENE.frames).fill(SCENE.confidence),
		})),
		association: {
			// the tracker's per-frame identity assignments; on synthetic GT they are all
			// correct, so M4 = 0. value is the projected box around the fighter.
			observations: SCENE.subjects.flatMap((s) => {
				const g = gt[s.trackId];
				return frameIndex.map((f) => {
					const [u, v] = projectToPixels(g.rootWorld[f], SCENE.K, R, t);
					return {
						frameIndex: f,
						trackId: s.trackId,
						assignedSubjectId: s.subjectId,
						evidence: "bbox",
						value: [u - 20, v - 160, 40, 160],
					};
				});
			}),
			groundTruth: SCENE.subjects.flatMap((s) =>
				SCENE.scoredFrames.map((f) => ({ frameIndex: f, trackId: s.trackId, subjectId: s.subjectId })),
			),
		},
		separation: {
			scoredFrameIndex: SCENE.scoredFrames,
			// same hypot expression the measurer evaluates, so M6 = 0 is exact, not rounded
			annotatedSeparationM: SCENE.scoredFrames.map((f) =>
				Math.hypot(
					gt.p0.rootWorld[f][0] - gt.p1.rootWorld[f][0],
					gt.p0.rootWorld[f][1] - gt.p1.rootWorld[f][1],
					gt.p0.rootWorld[f][2] - gt.p1.rootWorld[f][2],
				),
			),
		},
		provenance: {
			command: "node tools/ingest/feasibility/make-synthetic.mjs",
			sourceUrl: "",
			licence: "none (synthetic)",
			sourceSha256: rawTrack.sha256,
			trimStartS: SCENE.trimStartS,
			trimEndS: SCENE.trimStartS + SCENE.frames / SCENE.fps,
			gvhmrCommit: "", // no GVHMR run happened: this fixture is synthetic
			weightsSha256: "",
			annotationPath: "test/ingest/fixtures/solver-output/synthetic-boxing-01/annotation.json",
		},
	};
	doc.sha256 = sha256Of(doc);
	return doc;
}

export function buildSyntheticScene() {
	const { R, t } = lookAtExtrinsics(SCENE.cameraCentre, SCENE.cameraLookAt, SCENE.cameraUp);
	const gt = { p0: groundTruth("p0"), p1: groundTruth("p1") };
	const rawTrack = buildRawTrack(gt, R, t);
	const floorFrame = buildFloorFrame(R, t);
	const annotation = buildAnnotation(gt);
	const fixtures = {
		"contact-head": buildFixture("contact-head", gt, rawTrack, floorFrame, annotation, R, t),
		"lowest-foot": buildFixture("lowest-foot", gt, rawTrack, floorFrame, annotation, R, t),
		"manual-anchor": buildFixture("manual-anchor", gt, rawTrack, floorFrame, annotation, R, t),
	};
	return { rawTrack, floorFrame, annotation, fixtures };
}

// --- CLI -------------------------------------------------------------------------------

export function writeAllFixtures() {
	const out = buildSyntheticScene();
	const dir = new URL("../../../test/ingest/fixtures/solver-output/synthetic-boxing-01/", import.meta.url);
	mkdirSync(dir, { recursive: true });
	const files = [
		["rawtrack.json", out.rawTrack],
		["floorframe.json", out.floorFrame],
		["annotation.json", out.annotation],
		["contact-head.json", out.fixtures["contact-head"]],
		["lowest-foot.json", out.fixtures["lowest-foot"]],
		["manual-anchor.json", out.fixtures["manual-anchor"]],
	];
	const paths = [];
	for (const [name, doc] of files) {
		const url = new URL(name, dir);
		writeFileSync(url, JSON.stringify(doc, null, 2) + "\n");
		paths.push(url.pathname);
	}
	return paths;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
	console.log("wrote:\n" + writeAllFixtures().join("\n"));
}
